const std = @import("std");
const testing = std.testing;
const Allocator = std.mem.Allocator;

const sema = @import("sema.zig");
const ast = @import("ast.zig");
const trie = @import("trie.zig");
const match_compiler = @import("codegen/match.zig");
const constructors = @import("codegen/constructors.zig");
const extractors = @import("codegen/extractors.zig");

/// Code generation options.
pub const CodegenOptions = struct {
    /// Prefix for generated functions.
    prefix: []const u8 = "",
    /// Include debug comments.
    debug_comments: bool = false,
};

/// Zig code generator for ISLE rules.
pub const Codegen = struct {
    /// Type environment.
    typeenv: *const sema.TypeEnv,
    /// Term environment.
    termenv: *const sema.TermEnv,
    /// Compiled rules.
    rules: []const sema.Rule,
    /// Output buffer.
    output: std.ArrayList(u8),
    /// Allocator.
    allocator: Allocator,

    const Self = @This();

    pub fn init(
        allocator: Allocator,
        typeenv: *const sema.TypeEnv,
        termenv: *const sema.TermEnv,
        rules: []const sema.Rule,
    ) Self {
        return .{
            .typeenv = typeenv,
            .termenv = termenv,
            .rules = rules,
            .output = std.ArrayList(u8){},
            .allocator = allocator,
        };
    }

    pub fn deinit(self: *Self) void {
        self.output.deinit(self.allocator);
    }

    /// Generate Zig code from the compiled rules.
    pub fn generate(self: *Self, options: CodegenOptions) ![]const u8 {
        _ = options;
        self.output.clearRetainingCapacity();
        try self.emitPreamble();
        try self.emitContextStubs();
        try self.emitExternWrappers();
        try self.emitExtractors();
        try self.emitConstructors();
        return self.output.items;
    }

    fn emitPreamble(self: *Self) !void {
        const writer = self.output.writer(self.allocator);
        try writer.writeAll(
            \\// Auto-generated by ISLE compiler
            \\const std = @import("std");
            \\
            \\
        );
        try self.emitTupleTypes();
    }

    fn emitTupleTypes(self: *Self) !void {
        const writer = self.output.writer(self.allocator);
        for (self.typeenv.types.items) |ty| {
            if (ty != .tuple) continue;
            const tuple = ty.tuple;
            try writer.print("pub const {s} = struct {{\n", .{self.typeenv.symName(tuple.name)});
            for (tuple.fields, 0..) |field_ty, i| {
                const field_name = try self.getTypeName(field_ty);
                try writer.print("    field{d}: {s},\n", .{ i, field_name });
            }
            try writer.writeAll("};\n\n");
        }
    }

    fn emitContextStubs(self: *Self) !void {
        if (self.termenv.externs.count() == 0) return;
        const writer = self.output.writer(self.allocator);
        try writer.writeAll("pub const Context = struct {\n");
        var it = self.termenv.externs.iterator();
        while (it.next()) |entry| {
            const term_id = entry.key_ptr.*;
            const ext = entry.value_ptr.*;
            const term = self.termenv.getTerm(term_id);
            const sig = self.getTermSignature(term);

            if (ext.constructor) |func_sym| {
                const func_name = self.typeenv.symName(func_sym);
                try writer.print("    pub fn {s}(\n", .{func_name});
                try writer.writeAll("        self: *Context,\n");
                for (sig.params, 0..) |arg_ty, i| {
                    const ty_name = try self.getTypeName(arg_ty);
                    try writer.print("        arg{d}: {s},\n", .{ i, ty_name });
                }
                const ret_ty_name = try self.getTypeName(sig.ret_ty);
                const is_partial = term.kind == .decl and term.kind.decl.partial;
                const ret_prefix = if (is_partial) "!?" else "!";
                try writer.print("    ) {s}{s} {{\n", .{ ret_prefix, ret_ty_name });
                try writer.writeAll("        _ = self;\n");
                try writer.writeAll("        return error.Unimplemented;\n");
                try writer.writeAll("    }\n\n");
            }

            if (ext.extractor) |func_sym| {
                const func_name = self.typeenv.symName(func_sym);
                const input_ty = try self.getTypeName(sig.ret_ty);
                try writer.print("    pub fn {s}(\n", .{func_name});
                try writer.writeAll("        self: *Context,\n");
                try writer.print("        input: {s},\n", .{input_ty});
                try writer.writeAll("    ) !?");
                try self.emitExtractorOutType(writer, sig.params, sig.ret_ty);
                try writer.writeAll(" {\n");
                try writer.writeAll("        _ = self;\n");
                try writer.writeAll("        return error.Unimplemented;\n");
                try writer.writeAll("    }\n\n");
            }
        }
        try writer.writeAll("    pub fn recordRule(self: *Context, rule_name: []const u8) void {\n");
        try writer.writeAll("        _ = self;\n");
        try writer.writeAll("        _ = rule_name;\n");
        try writer.writeAll("    }\n\n");
        try writer.writeAll("};\n\n");
    }

    fn emitExternWrappers(self: *Self) !void {
        const writer = self.output.writer(self.allocator);
        var it = self.termenv.externs.iterator();
        while (it.next()) |entry| {
            const term_id = entry.key_ptr.*;
            const ext = entry.value_ptr.*;
            const term = self.termenv.getTerm(term_id);
            const term_name = self.typeenv.symName(term.name);
            const sig = self.getTermSignature(term);

            if (ext.constructor) |func_sym| {
                const func_name = self.typeenv.symName(func_sym);
                const ret_ty_name = try self.getTypeName(sig.ret_ty);
                const ret_prefix = if (term.kind == .decl and term.kind.decl.partial) "!?" else "!";
                try writer.print("\npub fn constructor_{s}(\n", .{term_name});
                try writer.writeAll("    ctx: *Context,\n");
                for (sig.params, 0..) |arg_ty, i| {
                    const ty_name = try self.getTypeName(arg_ty);
                    try writer.print("    arg{d}: {s},\n", .{ i, ty_name });
                }
                try writer.print(") {s}{s} {{\n", .{ ret_prefix, ret_ty_name });
                try writer.print("    return ctx.{s}(", .{func_name});
                for (sig.params, 0..) |_, i| {
                    if (i > 0) try writer.writeAll(", ");
                    try writer.print("arg{d}", .{i});
                }
                try writer.writeAll(");\n}\n");
            }

            if (ext.extractor) |func_sym| {
                const func_name = self.typeenv.symName(func_sym);
                try writer.print("\npub fn extractor_{s}(\n", .{term_name});
                try writer.writeAll("    ctx: *Context,\n");
                const input_ty = try self.getTypeName(sig.ret_ty);
                try writer.print("    input: {s},\n", .{input_ty});
                try writer.writeAll(") !?");
                try self.emitExtractorOutType(writer, sig.params, sig.ret_ty);
                try writer.writeAll(" {\n");
                try writer.print("    return ctx.{s}(input);\n}\n", .{func_name});
            }
        }
    }

    fn emitExtractors(self: *Self) !void {
        var gen = extractors.ExtractorCodegen.init(self.allocator, self.typeenv, self.termenv);
        defer gen.deinit();

        for (self.termenv.terms.items) |term| {
            if (term.kind != .extractor) continue;
            const code = try gen.generateExtractor(term.id);
            try self.output.appendSlice(code);
        }
    }

    fn emitConstructors(self: *Self) !void {
        var term_rules = std.AutoHashMap(sema.TermId, std.ArrayList(usize)).init(self.allocator);
        defer {
            var it = term_rules.valueIterator();
            while (it.next()) |list| {
                list.deinit(self.allocator);
            }
            term_rules.deinit();
        }

        for (self.rules, 0..) |rule, i| {
            const term_id = switch (rule.pattern) {
                .term => |t| t.term_id,
                else => continue,
            };
            const entry = try term_rules.getOrPut(term_id);
            if (!entry.found_existing) {
                entry.value_ptr.* = std.ArrayList(usize){};
            }
            try entry.value_ptr.append(self.allocator, i);
        }

        var mc = match_compiler.MatchCompiler.init(self.allocator, self.typeenv, self.termenv);
        var ctor_gen = try constructors.ConstructorGen.init(self.allocator, self.typeenv, self.termenv);
        defer ctor_gen.deinit();

        var it = term_rules.iterator();
        while (it.next()) |entry| {
            const term_id = entry.key_ptr.*;
            const indices = entry.value_ptr.items;
            const term = self.termenv.getTerm(term_id);

            if (term.kind != .decl) continue;
            if (self.termenv.getExtern(term_id)) |ext| {
                if (ext.constructor != null) continue;
            }

            std.mem.sort(usize, indices, self.rules, ruleIndexLess);

            var rules = std.ArrayList(sema.Rule){};
            defer rules.deinit(self.allocator);
            for (indices) |idx| {
                try rules.append(self.allocator, self.rules[idx]);
            }

            var ruleset = try mc.buildRuleSet(rules.items);
            defer ruleset.deinit();

            const code = try ctor_gen.genConstructor(term_id, &ruleset);
            try self.output.appendSlice(code);
        }
    }

    fn ruleIndexLess(rules: []const sema.Rule, a: usize, b: usize) bool {
        const pa = rules[a].prio;
        const pb = rules[b].prio;
        if (pa == pb) return a < b;
        return pa > pb;
    }

    fn emitRuleFunctions(self: *Self, options: CodegenOptions) !void {
        const writer = self.output.writer(self.allocator);

        // Group rules by term
        var term_rules = std.AutoHashMap(sema.TermId, std.ArrayList(usize)).init(self.allocator);
        defer {
            var it = term_rules.valueIterator();
            while (it.next()) |list| {
                list.deinit(self.allocator);
            }
            term_rules.deinit();
        }

        for (self.rules, 0..) |rule, i| {
            const term_id = switch (rule.pattern) {
                .term => |t| t.term_id,
                else => continue,
            };

            const entry = try term_rules.getOrPut(term_id);
            if (!entry.found_existing) {
                entry.value_ptr.* = std.ArrayList(usize){};
            }
            try entry.value_ptr.append(self.allocator, i);
        }

        // Generate a function for each term
        var it = term_rules.iterator();
        while (it.next()) |entry| {
            const term_id = entry.key_ptr.*;
            const rule_indices = entry.value_ptr.items;

            const term = self.termenv.getTerm(term_id);
            const term_name = self.typeenv.symName(term.name);

            // Function signature
            try writer.print(
                \\/// Generated lowering for {s}
                \\pub fn {s}{s}(
            , .{ term_name, options.prefix, term_name });

            // Generate parameters based on term signature
            const arg_tys = switch (term.kind) {
                .decl => |d| d.arg_tys,
                .extractor => |e| e.arg_tys,
                .extern_func => |e| e.arg_tys,
            };

            for (arg_tys, 0..) |arg_ty, idx| {
                const ty = self.typeenv.types.items[arg_ty.index()];
                const ty_name = switch (ty) {
                    .primitive => |p| self.typeenv.symName(p.name),
                    .tuple => |t| self.typeenv.symName(t.name),
                    .enum_type => |e| self.typeenv.symName(e.name),
                    else => "Value",
                };
                try writer.print("arg{d}: {s}", .{ idx, ty_name });
                if (idx < arg_tys.len - 1) {
                    try writer.writeAll(", ");
                }
            }

            const ret_ty = switch (term.kind) {
                .decl => |d| d.ret_ty,
                .extractor => |e| e.ret_ty,
                .extern_func => |e| e.ret_ty,
            };
            const ret_ty_obj = self.typeenv.types.items[ret_ty.index()];
            const ret_ty_name = switch (ret_ty_obj) {
                .primitive => |p| self.typeenv.symName(p.name),
                .tuple => |t| self.typeenv.symName(t.name),
                .enum_type => |e| self.typeenv.symName(e.name),
                else => "Value",
            };

            try writer.print(") {s} {{\n", .{ret_ty_name});

            // Emit rules for this term
            for (rule_indices, 0..) |rule_idx, i| {
                const rule = self.rules[rule_idx];

                if (options.debug_comments) {
                    try writer.print("    // Rule {d}\n", .{rule_idx});
                }

                // For now, just emit a simple return statement
                // Full implementation would generate pattern matching
                if (i == 0) {
                    try self.emitRuleBody(rule, 4);
                }
            }

            // Default return for unmatched patterns
            try writer.writeAll("    return error.NoMatch;\n");
            try writer.writeAll("}\n\n");
        }
    }

    fn emitRuleBody(self: *Self, rule: sema.Rule, indent: usize) !void {
        const writer = self.output.writer(self.allocator);

        // Emit pattern matching
        try self.emitIndent(indent);
        try writer.writeAll("// Pattern: ");
        try self.emitPattern(rule.pattern);
        try writer.writeByte('\n');

        // Emit expression evaluation
        try self.emitIndent(indent);
        try writer.writeAll("return ");
        try self.emitExpr(rule.expr);
        try writer.writeAll(";\n");
    }

    fn emitPattern(self: *Self, pattern: sema.Pattern) !void {
        const writer = self.output.writer(self.allocator);

        switch (pattern) {
            .var_pat => |v| {
                const name = self.typeenv.symName(v.name);
                try writer.writeAll(name);
            },
            .term => |t| {
                const term = self.termenv.getTerm(t.term_id);
                const name = self.typeenv.symName(term.name);
                try writer.print("({s}", .{name});
                for (t.args) |arg| {
                    try writer.writeByte(' ');
                    try self.emitPattern(arg);
                }
                try writer.writeByte(')');
            },
            else => {
                try writer.writeAll("<pattern>");
            },
        }
    }

    fn emitExpr(self: *Self, expr: sema.Expr) !void {
        const writer = self.output.writer(self.allocator);

        switch (expr) {
            .var_expr => |v| {
                const name = self.typeenv.symName(v.name);
                try writer.writeAll(name);
            },
            .term => |t| {
                const term = self.termenv.getTerm(t.term_id);
                const name = self.typeenv.symName(term.name);
                try writer.print("{s}(", .{name});
                for (t.args, 0..) |arg, i| {
                    if (i > 0) try writer.writeAll(", ");
                    try self.emitExpr(arg);
                }
                try writer.writeByte(')');
            },
            else => {
                try writer.writeAll("error.Unimplemented");
            },
        }
    }

    fn emitIndent(self: *Self, count: usize) !void {
        const writer = self.output.writer(self.allocator);
        var i: usize = 0;
        while (i < count) : (i += 1) {
            try writer.writeByte(' ');
        }
    }

    /// Optimize rule ordering by sorting by priority and specificity.
    /// Higher priority rules come first, and within each priority group,
    /// more specific patterns come before general ones.
    pub fn optimizeMatches(self: *Self, rule_indices: []usize) !void {
        if (rule_indices.len <= 1) return;

        // Sort by composite key: (priority desc, specificity desc)
        const Context = struct {
            rules: []const sema.Rule,
            codegen: *const Codegen,

            fn lessThan(ctx: @This(), a_idx: usize, b_idx: usize) bool {
                const a = ctx.rules[a_idx];
                const b = ctx.rules[b_idx];

                // First: Higher priority comes first
                if (a.prio != b.prio) {
                    return a.prio > b.prio;
                }

                // Within same priority: More specific patterns first
                const a_score = ctx.codegen.specificityScore(a.pattern);
                const b_score = ctx.codegen.specificityScore(b.pattern);
                return a_score > b_score;
            }
        };

        const ctx = Context{ .rules = self.rules, .codegen = self };
        std.mem.sort(usize, rule_indices, ctx, Context.lessThan);
    }

    /// Compute specificity score for a pattern.
    /// Higher score = more specific pattern.
    fn specificityScore(self: *const Self, pattern: sema.Pattern) usize {
        return switch (pattern) {
            // Constant patterns are most specific
            .const_bool, .const_int => 100,

            // Constructor patterns: base score + sum of argument scores
            .term => |t| blk: {
                var score: usize = 50;
                for (t.args) |arg| {
                    score += self.specificityScore(arg);
                }
                break :blk score;
            },

            // Variable bindings: medium specificity
            .var_pat => 10,

            // And-patterns: sum of sub-pattern scores
            .and_pat => |a| blk: {
                var score: usize = 0;
                for (a.subpats) |subpat| {
                    score += self.specificityScore(subpat);
                }
                break :blk score;
            },

            // Bind pattern: inherits sub-pattern score
            .bind_pattern => |b| self.specificityScore(b.subpat.*),

            // Wildcard is least specific
            .wildcard => 0,
        };
    }

    /// Generate a constructor function for a given term.
    /// Constructors build values from components.
    pub fn genConstructor(
        self: *Self,
        term_id: sema.TermId,
        rule_indices: []const usize,
    ) !void {
        const writer = self.output.writer(self.allocator);
        const term = self.termenv.getTerm(term_id);
        const term_name = self.typeenv.symName(term.name);

        const decl = switch (term.kind) {
            .decl => |d| d,
            else => return error.NotAConstructor,
        };

        // Function signature
        try writer.print("\n/// Constructor for {s}\n", .{term_name});
        try writer.print("pub fn constructor_{s}(\n", .{term_name});
        try writer.writeAll("    ctx: *Context,\n");

        // Parameters
        for (decl.arg_tys, 0..) |arg_ty, i| {
            const ty_name = try self.getTypeName(arg_ty);
            try writer.print("    arg{d}: {s},\n", .{ i, ty_name });
        }

        // Return type
        const ret_ty_name = try self.getTypeName(decl.ret_ty);
        if (decl.partial) {
            try writer.print(") !?{s} {{\n", .{ret_ty_name});
        } else {
            try writer.print(") !{s} {{\n", .{ret_ty_name});
        }

        // Emit rule matching logic
        if (rule_indices.len > 0) {
            for (rule_indices) |rule_idx| {
                const rule = self.rules[rule_idx];
                try self.emitRuleBody(rule, 4);
            }
        }

        // Default: error for no match
        if (decl.partial) {
            try writer.writeAll("    return null;\n");
        } else {
            try writer.writeAll("    return error.NoMatch;\n");
        }

        try writer.writeAll("}\n");
    }

    /// Generate an extractor function for a given term.
    /// Extractors decompose values and can fail.
    pub fn genExtractor(
        self: *Self,
        term_id: sema.TermId,
        rule_indices: []const usize,
    ) !void {
        const writer = self.output.writer(self.allocator);
        const term = self.termenv.getTerm(term_id);
        const term_name = self.typeenv.symName(term.name);

        const extractor = switch (term.kind) {
            .extractor => |e| e,
            else => return error.NotAnExtractor,
        };

        // Function signature
        try writer.print("\n/// Extractor for {s}\n", .{term_name});
        try writer.print("pub fn extractor_{s}(\n", .{term_name});
        try writer.writeAll("    ctx: *Context,\n");

        // Input parameter
        try writer.print("    input: {s},\n", .{try self.getTypeName(extractor.ret_ty)});

        // Parameters
        for (extractor.arg_tys, 0..) |arg_ty, i| {
            const ty_name = try self.getTypeName(arg_ty);
            try writer.print("    arg{d}: {s},\n", .{ i, ty_name });
        }

        // Return type (fallible)
        const ret_ty_name = try self.getTypeName(extractor.ret_ty);
        try writer.print(") ?{s} {{\n", .{ret_ty_name});

        // Emit extraction logic
        if (rule_indices.len > 0) {
            for (rule_indices) |rule_idx| {
                const rule = self.rules[rule_idx];
                try self.emitRuleBody(rule, 4);
            }
        }

        // Default: null for failed extraction
        try writer.writeAll("    return null;\n");
        try writer.writeAll("}\n");
    }

    /// Generate the main lowering dispatch function.
    pub fn genLower(self: *Self, term_rules: std.AutoHashMap(sema.TermId, std.ArrayList(usize))) !void {
        const writer = self.output.writer(self.allocator);

        try writer.writeAll(
            \\
            \\/// Main lowering entry point
            \\pub fn lower(ctx: *Context, value: Value) !LoweredValue {
            \\    return switch (value.op) {
            \\
        );

        var it = term_rules.iterator();
        while (it.next()) |entry| {
            const term_id = entry.key_ptr.*;
            _ = entry.value_ptr.items; // rule_indices not used yet

            const term = self.termenv.getTerm(term_id);
            const term_name = self.typeenv.symName(term.name);

            const arg_tys = switch (term.kind) {
                .decl => |d| d.arg_tys,
                else => continue,
            };

            try writer.print("        .{s} => {{\n", .{term_name});

            // Extract operands
            for (arg_tys, 0..) |_, i| {
                try writer.print("            const arg{d} = value.operand({d});\n", .{ i, i });
            }

            // Call constructor
            try writer.print("            return constructor_{s}(ctx", .{term_name});
            for (0..arg_tys.len) |i| {
                try writer.print(", arg{d}", .{i});
            }
            try writer.writeAll(");\n");
            try writer.writeAll("        },\n");
        }

        try writer.writeAll(
            \\        else => return error.UnsupportedOperation,
            \\    };
            \\}
            \\
        );
    }

    /// Get the Zig type name for a type ID.
    fn getTypeName(self: *const Self, type_id: sema.TypeId) ![]const u8 {
        const ty = self.typeenv.types.items[type_id.index()];
        return switch (ty) {
            .primitive => |p| self.typeenv.symName(p.name),
            .tuple => |t| self.typeenv.symName(t.name),
            .enum_type => |e| self.typeenv.symName(e.name),
            else => "Value",
        };
    }

    fn emitExtractorOutType(
        self: *const Self,
        writer: anytype,
        arg_tys: []const sema.TypeId,
        ret_ty: sema.TypeId,
    ) !void {
        if (arg_tys.len == 0) {
            try writer.writeAll(try self.getTypeName(ret_ty));
            return;
        }

        try writer.writeAll("struct { ");
        for (arg_tys, 0..) |arg_ty, i| {
            if (i > 0) try writer.writeAll(", ");
            try writer.print("arg{d}: {s}", .{ i, try self.getTypeName(arg_ty) });
        }
        try writer.writeAll(" }");
    }
};

